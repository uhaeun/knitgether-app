import Foundation

/// 로그아웃처럼 로컬 저장소를 비우기 전에, 아직 서버에 올리지 못한 것이 있는지 확인하는 통로.
///
/// 계정별 캐시 폴더(`RemoteCaches/<host>/<계정id>/`)는 이름과 달리 순수 캐시가 아니다.
/// 그 안의 `projects.json` 같은 파일에는 서버에서 받아온 항목과 아직 올리지 못한 항목이
/// 함께 있고, 후자는 유일한 원본이다. 그래서 폴더를 통째로 지우면 계정 노출(DEF-05~07)은
/// 닫히지만 사용자가 만든 작업이 무통보로 사라진다. 치명도 3위를 고치면서 1위를 여는 교환이라
/// 삭제 전에 올릴 수 있는 것은 올리고, 남은 것은 세어서 사용자에게 알린다.
protocol OfflineSyncFlushable {
    /// 미동기화 항목을 업로드 시도하고, 그러고도 남은 개수를 돌려준다.
    ///
    /// 0이면 로컬을 지워도 잃을 것이 없다. 0이 아니면 그만큼이 이 기기에만 있는 상태다.
    /// 네트워크가 없거나 서버가 거부하면 시도만 하고 개수는 줄지 않는다.
    func flushPendingChanges() async -> Int
}
